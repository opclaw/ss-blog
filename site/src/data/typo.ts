// Типографика чисел и знаков для посадочных-разделов.
//
// Зачем отдельный модуль: вёрстка правит то, что видно на экране, но не может
// удержать вместе «150 000 ₽». Обычный пробел внутри числа — законная точка переноса,
// и на узком экране цена рвалась на «150» / «000 ₽», а знак ₽ уезжал на свою строку.
// Здесь одна функция, которая расставляет неразрывные пробелы там, где перенос читается
// как ошибка: между разрядами числа, перед единицами (₽, %, мин, мес) и перед тире.
//
// Применяется к строкам раздела на входе в компоненты (LandingHero, LdSection, LdCards,
// LdPrices, LdFaq, LdLinks, HeroPanel) и к подписям интерактива на страницах.
// Тексты блога не трогаем: там своя вёрстка и своя проверка контента.

const NBSP = '\u00A0';

/** Единицы, которые не должны отрываться от числа: «60 000 ₽», «20 %», «45 мин». */
const UNITS = '₽|%|₽\\/мес|₽\\/год|%\\/мес|%\\/год|ч|мин|мес|шт|млн|млрд';
// После единицы не должно идти слово на кириллице: «мин» в «минуты» — не единица.
const UNIT_END = '(?![а-яё])';

export function typo(s: string): string;
export function typo(s: string | undefined): string | undefined;
export function typo(s: string | undefined): string | undefined {
  if (!s) return s;
  return (
    s
      // двойные и лишние пробелы: «продаж:  цена» → «продаж: цена»
      .replace(/[ \t]{2,}/g, ' ')
      // тире не должно начинать строку
      .replace(/ — /g, `${NBSP}— `)
      // разряды числа: 50 000 → 50 000, 1 800 000 → 1 800 000
      .replace(/(\d)\s(?=\d{3}(?!\d))/g, `$1${NBSP}`)
      // число и его единица: 60 000 ₽ / 20 % / 45 мин
      .replace(new RegExp(`(\\d)\\s(?=(?:${UNITS})${UNIT_END})`, 'g'), `$1${NBSP}`)
  );
}

/** То же для массива строк: цены, пункты пакетов, вопросы. */
export function typoAll(list: string[]): string[];
export function typoAll(list: string[] | undefined): string[] | undefined;
export function typoAll(list: string[] | undefined): string[] | undefined {
  return list?.map(typo);
}
