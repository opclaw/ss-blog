def calc(inputs, main, rows, note, n: int = 1, **kw) -> dict:
    """Компонент Calc: входы и выходы — списки словарей, main — (expr, label, unit, dig)."""
    code = (f'<Calc fig={{0}} title="{{TITLE}}" inputs={{mgIn{n}}} '
            f'main={{{{ expr: \'{main[0]}\', label: \'{main[1]}\', unit: \'{main[2]}\', dig: {main[3]} }}}} '
            f'rows={{mgRows{n}}} note="{{NOTE}}" />')
    consts = {
        f'mgIn{n}': 'const mgIn%d = %s;' % (n, json.dumps(inputs, ensure_ascii=False)),
        f'mgRows{n}': 'const mgRows%d = %s;' % (n, json.dumps(rows, ensure_ascii=False)),
    }
    return {'component': 'Calc', 'code': code, 'consts': consts, 'note': note, **kw}


def timeline(title, stages, note, **kw) -> dict:
    code = f'<Timeline fig={{0}} title="{{TITLE}}" stages={{mgTl}} note="{{NOTE}}" />'
    return {'component': 'Timeline', 'code': code, 'title': title, 'note': note, **kw,
            'consts': {'mgTl': 'const mgTl = ' + json.dumps(stages, ensure_ascii=False) + ';'}}


def put(slug: str, breadcrumb: str, hero_variant: str, hero_labels: list, intro: str, kits: list, after_calc='sec-6', after_tl='sec-7'):
    """Собирает запись манифеста: подставляет заголовки и примечания в код компонентов."""
    out_kits = []
    for k in kits:
        code = k['code']
        if k['component'] == 'Calc':
            code = code.replace('{TITLE}', k.get('title', 'Посчитайте эффект на своих цифрах'))
            code = code.replace('{NOTE}', k.get('note', 'Оценка по цифрам из статьи — подставьте свои.'))
        else:
            code = code.replace('{TITLE}', k.get('title', 'Пилот: что происходит по неделям'))
            code = code.replace('{NOTE}', k.get('note', 'Сроки и объём пилота подбираем под процесс — это стандартная схема 2–4 недель.'))
        pos = k.get('position', 'first_para')
        anchor = k.get('after', after_calc if k['component'] == 'Calc' else after_tl)
        out_kits.append({'component': k['component'], 'after': anchor, 'position': pos, 'code': code, 'consts': k['consts']})
    ART[slug] = {'breadcrumb': breadcrumb, 'dateModified': DATE,
                 'hero': {'variant': hero_variant, 'labels': hero_labels},
                 'intro': intro, 'kits': out_kits}


